//===========================================================================
// ov5640_sccb_cfg.v -- OV5640 SCCB configuration engine (write only)
//
// The board clock is 24 MHz (P13).  SCCB runs at 250 kHz (24 MHz / 96), i.e.
// a 4 us SCL period with four 1 us quarters per bit, which is inside the
// OV5640 100..400 kHz SCCB window and matches the vendor reference design.
//
// Bus handling (same convention as the official EG4S20NG88 OV5640 example):
//   * SCL is always driven push-pull by the FPGA.
//   * SDA is driven push-pull while the master sends a bit and released to Z
//     for the 9th (acknowledge / "don't care") slot of every byte.
//   * START pulls SDA low while SCL is high, STOP releases it while SCL is
//     high.  Both are clean levels, no reliance on external pull-ups.
//
// Sequence:
//   1. wait POWERUP_MS  (>= 20 ms, OV5640 needs it before the first write)
//   2. replay 250 writes of the public 640x480 RGB565 application-note table
//      (0x4300/0x501F = RGB565, 0x3808..0x380F = 640x480/1856x984,
//       0x3035/0x3036/0x3037 = PLL for 48 MHz PCLK from a 24 MHz XVCLK)
//   3. the reference table writes 0x3008 = 0x82 (software reset) as entry 2
//      and 0x3008 = 0x02 immediately after.  This engine inserts RESET_MS of
//      settle time between those two writes, which the OV5640 datasheet
//      requires and the reference table happens to omit.
//   4. cfg_done rises when the last STOP is complete and stays high.
//
// cfg_busy is high from power-up until cfg_done.  wr_count counts completed
// transactions, so a board bring-up LED/ILA can tell "stuck at entry 7" from
// "camera absent".  The engine intentionally ignores the SCCB acknowledge
// bit: SCCB's 9th slot is a don't-care and the OV5640 does not always drive
// it low, so it is not a usable error signal.
//
// The register table body below is generated by tools/gen_sccb_table.py from
// the public application-note sequence; values only, this encoding is ours.
//===========================================================================
