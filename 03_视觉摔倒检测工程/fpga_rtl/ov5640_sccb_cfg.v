                8'd237: begin tbl_addr = 16'h4004; tbl_data = 8'h02; end
                8'd238: begin tbl_addr = 16'h4713; tbl_data = 8'h03; end
                8'd239: begin tbl_addr = 16'h4407; tbl_data = 8'h04; end
                8'd240: begin tbl_addr = 16'h460C; tbl_data = 8'h22; end
                8'd241: begin tbl_addr = 16'h4837; tbl_data = 8'h22; end
                8'd242: begin tbl_addr = 16'h3824; tbl_data = 8'h02; end
                8'd243: begin tbl_addr = 16'h5001; tbl_data = 8'hA3; end
                8'd244: begin tbl_addr = 16'h3B07; tbl_data = 8'h0A; end
                8'd245: begin tbl_addr = 16'h503D; tbl_data = 8'h00; end
                8'd246: begin tbl_addr = 16'h3016; tbl_data = 8'h02; end
                8'd247: begin tbl_addr = 16'h301C; tbl_data = 8'h02; end
                8'd248: begin tbl_addr = 16'h3019; tbl_data = 8'h02; end
                8'd249: begin tbl_addr = 16'h3019; tbl_data = 8'h00; end
        // >>> OV5640_TABLE_END
        default: begin tbl_addr = 16'h300A; tbl_data = 8'h00; end
        endcase
    end

    // ----------------------------------------------------------- bit decode
    // Byte order on the wire: 0x78 (device 0x3C, write), address high,
    // address low, data.  bit_idx 8/17/26/35 are the acknowledge slots.
    wire is_ack = (bit_idx == 6'd8)  || (bit_idx == 6'd17) ||
                  (bit_idx == 6'd26) || (bit_idx == 6'd35);

    wire [5:0] nx = bit_idx + 6'd1;
    wire is_ack_n = (nx == 6'd8)  || (nx == 6'd17) ||
                    (nx == 6'd26) || (nx == 6'd35);

    wire [5:0] bitpos = (bit_idx <= 6'd7)  ? (6'd7  - bit_idx) :
                        (bit_idx <= 6'd16) ? (6'd16 - bit_idx) :
                        (bit_idx <= 6'd25) ? (6'd25 - bit_idx) :
                                             (6'd34 - bit_idx);

    wire [5:0] bitpos_n = (nx <= 6'd7)  ? (6'd7  - nx) :
                          (nx <= 6'd16) ? (6'd16 - nx) :
                          (nx <= 6'd25) ? (6'd25 - nx) :
                                          (6'd34 - nx);

    wire [7:0] tx_byte = (bit_idx <= 6'd7)  ? 8'h78 :
                         (bit_idx <= 6'd16) ? cur_addr[15:8] :
                         (bit_idx <= 6'd25) ? cur_addr[7:0]  : cur_data;

    wire [7:0] tx_byte_n = (nx <= 6'd7)  ? 8'h78 :
                           (nx <= 6'd16) ? cur_addr[15:8] :
                           (nx <= 6'd25) ? cur_addr[7:0]  : cur_data;

    wire bit_val   = tx_byte[bitpos[2:0]];
    wire bit_val_n = tx_byte_n[bitpos_n[2:0]];

    // ------------------------------------------------------------ sequencer
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state    <= S_POWER;
            qcnt     <= 16'd0;
            phase    <= 2'd0;
            stop_ph  <= 2'd0;
            bit_idx  <= 6'd0;
            idx      <= 8'd0;
            cur_addr <= 16'h300A;
            cur_data <= 8'h00;
            scl      <= 1'b1;
            sda_oe   <= 1'b1;
            sda_out  <= 1'b1;
            pwr_cnt  <= 19'd0;
            rst_cnt  <= 17'd0;
            cfg_done <= 1'b0;
            wr_count <= 8'd0;
        end else begin
            case (state)
            // ------------------------------------------------- power-up wait
            S_POWER: begin
                scl     <= 1'b1;
                sda_oe  <= 1'b1;
                sda_out <= 1'b1;
                if (PWR_CYCLES == 0 || pwr_cnt >= PWR_CYCLES - 1)
                    state <= S_LOAD;
                else
                    pwr_cnt <= pwr_cnt + 19'd1;
            end

            // ---------------------------------------------------- latch entry
            S_LOAD: begin
                cur_addr <= tbl_addr;
                cur_data <= tbl_data;
                bit_idx  <= 6'd0;
                qcnt     <= 16'd0;
                phase    <= 2'd0;
                state    <= S_START;
            end

            // ------------------------------------------------ START condition
            // SCL is already high; pull SDA down, hold t_HD;STA, then SCL low.
            S_START: begin
                scl     <= 1'b1;
                sda_oe  <= 1'b1;
                sda_out <= 1'b0;
                if (qcnt == QUARTER - 1) begin
                    qcnt    <= 16'd0;
                    scl     <= 1'b0;
                    sda_out <= bit_val;      // first bit of 0x78 (=0 here)
                    state   <= S_BITS;
                end else begin
                    qcnt <= qcnt + 16'd1;
                end
            end

            // ------------------------------------------------------- bit engine
            // quarter 0: SCL low, SDA stable (was set in the previous phase)
            // quarter 1: SCL high  - slave samples SDA
            // quarter 2: SCL high
            // quarter 3: SCL low   - SDA moves to the next bit
            S_BITS: begin
                if (qcnt != QUARTER - 1) begin
                    qcnt <= qcnt + 16'd1;
                end else begin
                    qcnt <= 16'd0;
                    case (phase)
                    2'd0: begin scl <= 1'b1; phase <= 2'd1; end
                    2'd1: begin scl <= 1'b1; phase <= 2'd2; end
                    2'd2: begin scl <= 1'b0; phase <= 2'd3; end
                    default: begin
                        scl   <= 1'b0;
                        phase <= 2'd0;
                        if (bit_idx == 6'd35) begin
                            state <= S_STOP;
                        end else begin
                            bit_idx <= nx;
                            if (is_ack_n) begin
                                sda_oe  <= 1'b0;      // release for 9th slot
                                sda_out <= 1'b1;
                            end else begin
                                sda_oe  <= 1'b1;
                                sda_out <= bit_val_n;
                            end
                        end
                    end
                    endcase
                end
            end

            // ------------------------------------------------- STOP condition
            S_STOP: begin
                if (qcnt != QUARTER - 1) begin
                    qcnt <= qcnt + 16'd1;
                end else begin
                    qcnt <= 16'd0;
                    case (stop_ph)
                    2'd0: begin sda_oe <= 1'b1; sda_out <= 1'b0; stop_ph <= 2'd1; end
                    2'd1: begin scl    <= 1'b1;                  stop_ph <= 2'd2; end
                    2'd2: begin sda_out <= 1'b1;                 stop_ph <= 2'd3; end
                    default: begin
                        scl     <= 1'b1;
                        sda_oe  <= 1'b1;
                        sda_out <= 1'b1;
                        stop_ph <= 2'd0;
                        wr_count <= wr_count + 8'd1;
                        state   <= S_GAP;
                    end
                    endcase
                end
            end

            // ------------------------------------------------ inter-write gap
            S_GAP: begin
                scl     <= 1'b1;
                sda_oe  <= 1'b1;
                sda_out <= 1'b1;
                if (qcnt != QUARTER * 4 - 1) begin
                    qcnt <= qcnt + 16'd1;
                end else begin
                    qcnt <= 16'd0;
                    if (idx == RESET_IDX) begin
                        rst_cnt <= 17'd0;
                        state   <= S_RSW;
                    end else if (idx == LAST_IDX) begin
                        cfg_done <= 1'b1;
                        state    <= S_DONE;
                    end else begin
                        idx   <= idx + 8'd1;
                        state <= S_LOAD;
                    end
                end
            end

            // ------------------------------ 0x3008=0x82 settle before 0x02
            S_RSW: begin
                if (RST_CYCLES == 0 || rst_cnt >= RST_CYCLES - 1) begin
                    idx   <= idx + 8'd1;
                    state <= S_LOAD;
                end else begin
                    rst_cnt <= rst_cnt + 17'd1;
                end
            end

            // ----------------------------------------------------------- done
            default: begin
                scl     <= 1'b1;
                sda_oe  <= 1'b1;
                sda_out <= 1'b1;
                cfg_done <= 1'b1;
            end
            endcase
        end
    end

endmodule
